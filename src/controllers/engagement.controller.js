// W10 AP38: attribution, independence and the 60-day assembly. Every write is one person's act on their
// own behalf (or the assigned reviewer's); the service decides who may do which.
const assuranceHandler = (work) => async (req, res, next) => {
  try {
    const assurance = await work({
      engagementId: req.params.id,
      firmId: req.user.firmId,
      actorUserId: req.user.id,
      input: req.body || {},
      entryId: req.params.entryId,
    });
    return res.json({ ok: true, assurance });
  } catch (error) {
    return next(error);
  }
};
export const getAssurance = assuranceHandler((args) => showAssurance(args));
export const postIndependence = assuranceHandler(confirmIndependence);
export const postReportDate = assuranceHandler(setReportDate);
export const postAssemble = assuranceHandler(assembleFile);
export const postModification = assuranceHandler(logModification);
export const postTimeEntry = assuranceHandler(addTimeEntry);
export const postVoidTimeEntry = assuranceHandler(voidTimeEntry);

