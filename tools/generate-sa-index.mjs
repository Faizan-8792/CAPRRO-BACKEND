// tools/generate-sa-index.mjs
//
// W10 AP33. Writes the Standards on Auditing index into both clients from src/data/sa-index.js, so there
// is one table and two copies that cannot quietly differ:
//   ../audit-nlp-extension/data/sa-index.json
//   ../apps/desktop-native/src/CaPro.Desktop.Core/Audit/StandardsIndex.generated.cs
//
//   node tools/generate-sa-index.mjs            write both
//   node tools/generate-sa-index.mjs --check    exit 1 if either differs (a missing client tree is skipped)
//
// The check is also run by tests/sa-index-contract.mjs, so a table edited without regenerating fails the
// gates. Exit codes are set, never process.exit() after I/O (CLAUDE.md section 12).

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { NOT_RECORDED, SA_INDEX } from "../src/data/sa-index.js";

const here = dirname(fileURLToPath(import.meta.url));
const parent = join(here, "..", "..");
const targets = {
  json: join(parent, "audit-nlp-extension", "data", "sa-index.json"),
  csharp: join(parent, "apps", "desktop-native", "src", "CaPro.Desktop.Core", "Audit", "StandardsIndex.generated.cs"),
};

export function renderJson() {
  const body = {
    generatedFrom: "capro-backend/src/data/sa-index.js",
    notRecorded: NOT_RECORDED,
    entries: SA_INDEX.map((e) => ({ number: e.number, title: e.title, group: e.group, effectiveDate: e.effectiveDate })),
  };
  return `${JSON.stringify(body, null, 2)}\n`;
}

const cs = (value) => JSON.stringify(value); // ASCII-only table, so JSON escapes are valid C# escapes

export function renderCSharp() {
  const rows = SA_INDEX.map(
    (e) => `        new StandardsIndexEntry(${e.number}, ${cs(e.title)}, ${cs(e.group)}, ${e.effectiveDate === null ? "null" : cs(e.effectiveDate)}),`,
  ).join("\n");
  return `// <auto-generated>
// Generated by capro-backend/tools/generate-sa-index.mjs from capro-backend/src/data/sa-index.js.
// Do not edit by hand: edit the table, run the generator, commit all three files.
// </auto-generated>

#nullable enable

namespace CaPro.Desktop.Core.Audit;

/// <summary>One Standard on Auditing: number, title and group. <see cref="EffectiveDate"/> is an ISO day or null when not recorded.</summary>
public sealed record StandardsIndexEntry(int Number, string Title, string Group, string? EffectiveDate);

public static class StandardsIndexData
{
    public const string NotRecorded = ${cs(NOT_RECORDED)};

    public static readonly IReadOnlyList<StandardsIndexEntry> Entries =
    [
${rows}
    ];
}
`;
}

const normalise = (text) => text.replace(/\r\n/g, "\n");

function main() {
  const check = process.argv.includes("--check");
  const wanted = { json: renderJson(), csharp: renderCSharp() };
  let drift = 0;
  for (const [name, path] of Object.entries(targets)) {
    const folder = dirname(path);
    if (!existsSync(join(folder, ".."))) {
      console.log(`skipped ${name}: ${folder} is not here`);
      continue;
    }
    const current = existsSync(path) ? normalise(readFileSync(path, "utf8")) : null;
    if (current === wanted[name]) {
      console.log(`current  ${name}`);
      continue;
    }
    if (check) {
      console.error(`DRIFT    ${name}: ${path} differs from src/data/sa-index.js - run node tools/generate-sa-index.mjs`);
      drift += 1;
    } else {
      mkdirSync(folder, { recursive: true });
      writeFileSync(path, wanted[name], "utf8");
      console.log(`wrote    ${name}`);
    }
  }
  process.exitCode = drift ? 1 : 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
